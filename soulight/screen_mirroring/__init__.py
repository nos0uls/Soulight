# screen_mirroring package
#
# Этот пакет хранит фундамент для режима Ambilight / Screen Mirroring.
# Здесь лежат модули для:
# - вычисления зон захвата по конфигурации LED
# - чтения кадра с экрана
# - усреднения цветов и сглаживания
#
# Импорты здесь специально минимальные.
# Это помогает не тянуть тяжёлые зависимости раньше времени.
